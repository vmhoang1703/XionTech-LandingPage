#!/usr/bin/env bash
# Local SonarQube instance manager (Docker).
#
# LOCAL-ONLY variant (XionTech Landing Page): each developer runs a throwaway
# SonarQube in Docker and the pre-push gate scans against it for every branch.
# This project never publishes to the shared XT SonarQube server.
#
# Usage:
#   ./local_sonar.sh up       # start the container, wait for UP, bootstrap a token
#   ./local_sonar.sh ensure   # up, but a no-op if it is already healthy
#   ./local_sonar.sh status   # print container + server status
#   ./local_sonar.sh down     # stop and remove the container (data volumes kept)
#   ./local_sonar.sh reset    # down + delete data volumes (fresh instance next up)
#   ./local_sonar.sh token    # print the bootstrapped token (for scripting)
#
# Credentials/token land in ~/.sonar-prepush-gate.env (outside every repo).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# One container serves every repo on this machine, so its admin password and
# token belong to the machine, not to a repo. Keeping them per-repo meant the
# second repo to install the gate found the password already rotated and could
# not bootstrap (HTTP 401 on change_password).
SONAR_LOCAL_STATE_FILE="${SONAR_LOCAL_STATE_FILE:-$HOME/.sonar-prepush-gate.env}"
LOCAL_ENV_FILE="$SONAR_LOCAL_STATE_FILE"

# One-time migration from the old per-repo location.
LEGACY_ENV_FILE="$SCRIPT_DIR/sonar.local.env"
if [ -f "$LEGACY_ENV_FILE" ] && [ ! -f "$LOCAL_ENV_FILE" ]; then
  mkdir -p "$(dirname "$LOCAL_ENV_FILE")"
  mv "$LEGACY_ENV_FILE" "$LOCAL_ENV_FILE"
  echo "[sonar-local] Moved local credentials to $LOCAL_ENV_FILE (shared by every repo on this machine)."
fi

# All of these can be overridden from sonar.env if a machine needs different
# ports/images (e.g. port 9000 already taken).
SONAR_LOCAL_IMAGE="${SONAR_LOCAL_IMAGE:-sonarqube:community}"
SONAR_LOCAL_CONTAINER="${SONAR_LOCAL_CONTAINER:-sonarqube-local}"
SONAR_LOCAL_NETWORK="${SONAR_LOCAL_NETWORK:-sonar-local-net}"
SONAR_LOCAL_PORT="${SONAR_LOCAL_PORT:-9000}"
SONAR_LOCAL_HOST_URL="${SONAR_LOCAL_HOST_URL:-http://localhost:$SONAR_LOCAL_PORT}"
SONAR_LOCAL_STARTUP_TIMEOUT="${SONAR_LOCAL_STARTUP_TIMEOUT:-420}"
SONAR_LOCAL_TOKEN_NAME="${SONAR_LOCAL_TOKEN_NAME:-prepush-gate}"

log() { echo "[sonar-local] $*"; }
die() { echo "[sonar-local] $*" >&2; exit 1; }

# This script rotates the admin password and mints tokens on whatever
# SONAR_LOCAL_HOST_URL names, so it must only ever be this machine.
# Only http://localhost:<port> or http://127.0.0.1:<port>, nothing after the
# port. A glob such as http://localhost:* would also accept
# http://localhost:1@remote.host/, which curl sends to remote.host.
LOCAL_URL_RE='^http://(localhost|127\.0\.0\.1):[0-9]+/?$'
if ! [[ "$SONAR_LOCAL_HOST_URL" =~ $LOCAL_URL_RE ]]; then
  die "SONAR_LOCAL_HOST_URL must be http://localhost:<port> or http://127.0.0.1:<port> (got '$SONAR_LOCAL_HOST_URL')."
fi

require_docker() {
  command -v docker >/dev/null 2>&1 || die "docker is not installed or not on PATH."
  docker info >/dev/null 2>&1 || die "The Docker daemon is not reachable. Start Docker Desktop and retry."
}

load_local_env() {
  if [ -f "$LOCAL_ENV_FILE" ]; then
    set -a
    # shellcheck disable=SC1090
    source "$LOCAL_ENV_FILE"
    set +a
  fi
}

write_local_env() {
  # Rewritten wholesale each time; this file only ever holds these two values.
  umask 077
  mkdir -p "$(dirname "$LOCAL_ENV_FILE")"
  cat > "$LOCAL_ENV_FILE" <<EOF
# Generated by local_sonar.sh — gitignored, per-machine. Safe to delete;
# 'local_sonar.sh reset && local_sonar.sh up' recreates it.
SONAR_LOCAL_ADMIN_PASSWORD=$SONAR_LOCAL_ADMIN_PASSWORD
SONAR_LOCAL_TOKEN=$SONAR_LOCAL_TOKEN
EOF
}

gen_password() {
  # SonarQube rejects weak/known passwords; this is random and never typed by a
  # human (the pre-push gate reads it from ~/.sonar-prepush-gate.env).
  local raw
  raw="$(head -c 24 /dev/urandom | base64 | tr -d '\n/+=' | cut -c1-20)"
  printf 'Lx9!%s' "$raw"
}

server_status() {
  curl -s -m 5 "$SONAR_LOCAL_HOST_URL/api/system/status" 2>/dev/null \
    | python -c "import sys,json;print(json.load(sys.stdin).get('status','?'))" 2>/dev/null \
    || echo "DOWN"
}

container_state() {
  docker inspect -f '{{.State.Status}}' "$SONAR_LOCAL_CONTAINER" 2>/dev/null || echo "absent"
}

token_is_valid() {
  [ -n "${SONAR_LOCAL_TOKEN:-}" ] || return 1
  curl -s -m 10 -u "$SONAR_LOCAL_TOKEN:" "$SONAR_LOCAL_HOST_URL/api/authentication/validate" 2>/dev/null \
    | grep -q '"valid":true'
}

start_container() {
  docker network inspect "$SONAR_LOCAL_NETWORK" >/dev/null 2>&1 \
    || docker network create "$SONAR_LOCAL_NETWORK" >/dev/null

  local state
  state="$(container_state)"
  case "$state" in
    running) log "Container $SONAR_LOCAL_CONTAINER already running." ; return ;;
    exited|created) log "Starting existing container $SONAR_LOCAL_CONTAINER..." ; docker start "$SONAR_LOCAL_CONTAINER" >/dev/null ; return ;;
  esac

  log "Creating container $SONAR_LOCAL_CONTAINER from $SONAR_LOCAL_IMAGE (first run pulls ~700MB)..."
  # SONAR_ES_BOOTSTRAP_CHECKS_DISABLE: the bundled Elasticsearch demands
  # vm.max_map_count=524288, which Docker Desktop/WSL2 does not set by default.
  # This is a local dev instance, not production, so the check is safe to skip.
  docker run -d \
    --name "$SONAR_LOCAL_CONTAINER" \
    --network "$SONAR_LOCAL_NETWORK" \
    -p "$SONAR_LOCAL_PORT:9000" \
    -e SONAR_ES_BOOTSTRAP_CHECKS_DISABLE=true \
    -e SONAR_TELEMETRY_ENABLE=false \
    -v sonarqube_local_data:/opt/sonarqube/data \
    -v sonarqube_local_extensions:/opt/sonarqube/extensions \
    -v sonarqube_local_logs:/opt/sonarqube/logs \
    "$SONAR_LOCAL_IMAGE" >/dev/null
}

wait_for_up() {
  log "Waiting for SonarQube to come up at $SONAR_LOCAL_HOST_URL (first boot takes 1-3 min)..."
  local waited=0 status
  while [ "$waited" -lt "$SONAR_LOCAL_STARTUP_TIMEOUT" ]; do
    status="$(server_status)"
    if [ "$status" = "UP" ]; then
      log "SonarQube is UP."
      return 0
    fi
    if [ "$(container_state)" != "running" ]; then
      docker logs --tail 30 "$SONAR_LOCAL_CONTAINER" 2>&1 || true
      die "Container stopped while starting up (see logs above)."
    fi
    sleep 5
    waited=$((waited + 5))
  done
  docker logs --tail 30 "$SONAR_LOCAL_CONTAINER" 2>&1 || true
  die "Timed out after ${SONAR_LOCAL_STARTUP_TIMEOUT}s waiting for SonarQube (see logs above)."
}

bootstrap_credentials() {
  # Fresh instance ships with admin/admin. Rotate it once, remember the new
  # password locally, then mint an analysis token.
  if [ -z "${SONAR_LOCAL_ADMIN_PASSWORD:-}" ]; then
    SONAR_LOCAL_ADMIN_PASSWORD="$(gen_password)"
    log "Rotating the default admin password..."
    local code
    code="$(curl -s -o /dev/null -w '%{http_code}' -m 20 -u "admin:admin" \
      -X POST "$SONAR_LOCAL_HOST_URL/api/users/change_password" \
      --data-urlencode "login=admin" \
      --data-urlencode "previousPassword=admin" \
      --data-urlencode "password=$SONAR_LOCAL_ADMIN_PASSWORD")"
    if [ "$code" != "204" ] && [ "$code" != "200" ]; then
      die "Could not set the admin password (HTTP $code). The instance may already be bootstrapped with a password this machine has lost — run './local_sonar.sh reset' to start clean."
    fi
  fi

  # Old token may be stale (e.g. after a reset) — revoke by name, then mint a
  # new one. Revoking a non-existent token is a no-op on SonarQube's side.
  curl -s -o /dev/null -m 20 -u "admin:$SONAR_LOCAL_ADMIN_PASSWORD" \
    -X POST "$SONAR_LOCAL_HOST_URL/api/user_tokens/revoke" \
    --data-urlencode "name=$SONAR_LOCAL_TOKEN_NAME" || true

  log "Generating analysis token '$SONAR_LOCAL_TOKEN_NAME'..."
  local resp
  resp="$(curl -s -m 20 -u "admin:$SONAR_LOCAL_ADMIN_PASSWORD" \
    -X POST "$SONAR_LOCAL_HOST_URL/api/user_tokens/generate" \
    --data-urlencode "name=$SONAR_LOCAL_TOKEN_NAME")"
  SONAR_LOCAL_TOKEN="$(echo "$resp" | python -c "import sys,json;print(json.load(sys.stdin).get('token',''))" 2>/dev/null || true)"
  [ -n "$SONAR_LOCAL_TOKEN" ] || die "Token generation failed: $resp"

  write_local_env
  log "Credentials written to $LOCAL_ENV_FILE"
}

cmd_up() {
  require_docker
  load_local_env
  start_container
  wait_for_up
  if token_is_valid; then
    log "Existing token still valid — reusing it."
  else
    bootstrap_credentials
  fi
  log "Ready: $SONAR_LOCAL_HOST_URL (admin / see $LOCAL_ENV_FILE)"
}

cmd_ensure() {
  load_local_env
  if [ "$(server_status)" = "UP" ] && token_is_valid; then
    return 0
  fi
  cmd_up
}

cmd_status() {
  load_local_env
  echo "container: $(container_state)"
  echo "server:    $(server_status) ($SONAR_LOCAL_HOST_URL)"
  if token_is_valid; then echo "token:     valid"; else echo "token:     missing/invalid"; fi
}

cmd_down() {
  require_docker
  docker rm -f "$SONAR_LOCAL_CONTAINER" >/dev/null 2>&1 || true
  log "Container removed. Data volumes kept — 'up' will restore the same instance."
}

cmd_reset() {
  require_docker
  cmd_down
  docker volume rm sonarqube_local_data sonarqube_local_extensions sonarqube_local_logs >/dev/null 2>&1 || true
  rm -f "$LOCAL_ENV_FILE"
  log "Volumes and saved credentials deleted. Next 'up' creates a fresh instance."
}

cmd_token() {
  load_local_env
  [ -n "${SONAR_LOCAL_TOKEN:-}" ] || die "No token yet — run './local_sonar.sh up' first."
  printf '%s\n' "$SONAR_LOCAL_TOKEN"
}

case "${1:-up}" in
  up)     cmd_up ;;
  ensure) cmd_ensure ;;
  status) cmd_status ;;
  down)   cmd_down ;;
  reset)  cmd_reset ;;
  token)  cmd_token ;;
  *)      die "Unknown command '${1}'. Use: up | ensure | status | down | reset | token" ;;
esac
